"""Render benchmark results as markdown (bench/results.md) and JSON (bench/results.json)."""

from __future__ import annotations

import json
from pathlib import Path

from .evaluate import PHRASINGS

SYSTEM_NAMES = {"agentindex": "AgentIndex", "bm25": "FTS5 bm25()", "grep": "grep"}
CONTEXT_WINDOW = 200_000
PHRASING_NAMES = {"question": "natural questions", "keywords": "search keywords"}


def write_results(results: dict, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    markdown, data = out / "results.md", out / "results.json"
    markdown.write_text(render_report(results) + "\n", encoding="utf-8")
    data.write_text(json.dumps(results, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return [markdown, data]


def render_report(results: dict, summary_only: bool = False) -> str:
    corpora = [c for c in results["corpora"] if c["n"]]
    env = results["environment"]
    cases = sum(c["n"] for c in corpora)
    lines = [
        "# Benchmark results",
        "",
        f"AgentIndex on {len(results['corpora'])} real knowledge bases, with {cases} questions"
        " taken from real tasks, each asked as a natural question and as search keywords."
        f" Generated by `python3 -m bench run` on {results['generated'][:10]} with agentindex"
        f" {env['agentindex']}, Python {env['python']} and SQLite {env['sqlite']}"
        f" ({env['platform']}). How it works:"
        " [knowledge/development/benchmarks.md](../knowledge/development/benchmarks.md).",
        "",
        "## Summary",
        "",
        *_summary(results),
    ]
    if summary_only:
        return "\n".join(lines)
    lines += ["", "## Retrieval by corpus", ""]
    for phrasing in PHRASINGS:
        lines += [f"Asked as {PHRASING_NAMES[phrasing]}: answer ranked first · in the top 3.", ""]
        lines += _retrieval_table(corpora, phrasing) + [""]
    if results.get("by_kind"):
        lines += ["## Retrieval by kind of question", "", *_kind_table(results), ""]
    lines += ["## Context cost", "", *_cost_table(results), "", "## Speed", ""]
    lines += _speed_table(results) + ["", "## Corpora", "", *_corpora_table(results)]
    lines += ["", "## Misses", "", *_misses(corpora)]
    return "\n".join(lines).rstrip()


def _summary(results: dict) -> list[str]:
    overall = results["overall"]
    rows = [
        "| | AgentIndex | FTS5 bm25() | grep |",
        "|---|---|---|---|",
    ]
    for key, label in (("hit1", "Answer ranked first"), ("hit3", "Answer in the top 3")):
        for phrasing in PHRASINGS:
            stats = overall["retrieval"][phrasing]
            cells = [_pct(stats[s][key]) for s in ("agentindex", "bm25", "grep")]
            low, high = stats["agentindex"][key + "_ci"]
            cells[0] = f"**{cells[0]}** ({_pct(low)}–{_pct(high)})"
            rows.append(f"| {label}, {PHRASING_NAMES[phrasing]} | " + " | ".join(cells) + " |")
    section = overall["section"]["question"]
    if section["rate"] is not None:
        rows.append(
            f"| Result points at the answering section | **{_pct(section['rate'])}** | – | – |"
        )
    note = (
        "Percentages are of all cases; AgentIndex's 95% confidence interval is in brackets."
        " The answering section is judged where the answer is one section of a longer doc"
        " and a relevant doc was in the top 3. What the lookups cost is under"
        " [context cost](#context-cost); what real agents spent is in [pilot.md](pilot.md)."
    )
    return rows + ["", note]


def _retrieval_table(corpora: list[dict], phrasing: str) -> list[str]:
    rows = [
        "| Corpus | Cases | AgentIndex | FTS5 bm25() | grep |",
        "|---|---|---|---|---|",
    ]
    for corpus in corpora:
        stats = corpus["retrieval"][phrasing]
        cells = [f"{_pct(stats[s]['hit1'])} · {_pct(stats[s]['hit3'])}" for s in SYSTEM_NAMES]
        cells[0] = f"**{cells[0]}**"
        rows.append(f"| {corpus['title']} | {corpus['n']} | " + " | ".join(cells) + " |")
    return rows


def _kind_table(results: dict) -> list[str]:
    rows = [
        "Natural questions, all corpora: answer ranked first · in the top 3.",
        "",
        "| Kind | Cases | AgentIndex | FTS5 bm25() | grep |",
        "|---|---|---|---|---|",
    ]
    for kind, stats in results["by_kind"].items():
        question = stats["question"]
        cells = [f"{_pct(question[s]['hit1'])} · {_pct(question[s]['hit3'])}" for s in SYSTEM_NAMES]
        cells[0] = f"**{cells[0]}**"
        n = question["agentindex"]["n"]
        rows.append(f"| {kind} | {n} | " + " | ".join(cells) + " |")
    return rows


def _cost_table(results: dict) -> list[str]:
    pointer = results["settings"]["pointer_tokens"]
    rows = [
        "Approximate tokens (characters / 4) of text a simulated agent reads. Loading everything"
        f" is paid in every session; AgentIndex costs a {pointer}-token CLAUDE.md pointer per"
        " session plus each lookup. Lookups are medians over natural questions, and misses"
        " count all their reads. The grep agent here reads whole files, which is an upper"
        " bound: real agents read the matching parts, and [pilot.md](pilot.md) has what they"
        " spent.",
        "",
        "| Corpus | Load everything | grep, reading whole files | AgentIndex, per lookup |"
        " Lookups before AgentIndex costs more |",
        "|---|---|---|---|---|",
    ]
    for corpus in results["corpora"]:
        if not corpus["n"]:
            continue
        tokens = corpus["tokens"]["question"]
        index_cost = tokens["agentindex"]["median"]
        breakeven = (corpus["tokens_total"] - pointer) // index_cost if index_cost else 0
        total = _num(corpus["tokens_total"])
        if corpus["tokens_total"] > CONTEXT_WINDOW:
            total += " (does not fit)"
        rows.append(
            f"| {corpus['title']} | {total} | {_num(tokens['grep']['median'])} |"
            f" **{_num(index_cost)}** | {_num(breakeven)} |"
        )
    rows += ["", f'"Does not fit": more than a {CONTEXT_WINDOW // 1000}k-token context window.']
    return rows


def _speed_table(results: dict) -> list[str]:
    rows = [
        "Building the index happens once, on the first query; later queries only check file"
        " sizes and times. In-process search includes that check, as in the MCP server. The"
        " CLI time is a whole `python3 -m agentindex search` process, start to output.",
        "",
        "| Corpus | Docs | Words | Build index | Search p50 | Search p95 | CLI search |",
        "|---|---|---|---|---|---|---|",
    ]
    for corpus in results["corpora"]:
        speed, times = corpus["speed"], corpus.get("search_ms") or {}
        cli = f"{speed['cli_ms']:.0f} ms" if speed["cli_ms"] else "–"
        rows.append(
            f"| {corpus['title']} | {_num(corpus['docs'])} | {_num(corpus['words'])} |"
            f" {speed['cold_index_s']:.2f} s | {_ms(times.get('p50'))} | {_ms(times.get('p95'))} |"
            f" {cli} |"
        )
    return rows


def _corpora_table(results: dict) -> list[str]:
    rows = [
        "Each corpus is pinned to a commit and indexed as it is, with no per-corpus tuning."
        " Questions were written from real merged PRs (or common tasks) without looking at the"
        " docs; the answers were labeled separately, and questions the docs do not answer were"
        " dropped. Two labelers worked independently on every question; the last column is how"
        " often they named the same answering doc when both found one.",
        "",
        "| Corpus | Source | Indexed | Questions kept / written | Labelers agreed |",
        "|---|---|---|---|---|",
    ]
    for corpus in results["corpora"]:
        how = (
            f"`{corpus['original']}` split with `agentindex import` into {corpus['docs']} docs"
            if corpus["kind"] == "import"
            else f"{corpus['docs']} docs"
        )
        source = f"[{corpus['url'].split('/')[3]}/{corpus['url'].split('/')[4]}]({corpus['url']})"
        agreement = (corpus.get("labeling") or {}).get("agreement") or {}
        agreed = (
            _pct(agreement["same_doc"] / agreement["both_answered"])
            if agreement.get("both_answered")
            else "–"
        )
        rows.append(
            f"| {corpus['title']} | {source} @ `{corpus['commit'][:10]}` ({corpus['license']}) |"
            f" {how} | {corpus['n']} / {corpus['written']} | {agreed} |"
        )
    return rows


def _misses(corpora: list[dict]) -> list[str]:
    lines = [
        "Cases where AgentIndex had no answering doc in its top 3, for either phrasing, with"
        " what it ranked first instead.",
        "",
    ]
    for corpus in corpora:
        missed = []
        for case in corpus["cases"]:
            for phrasing in PHRASINGS:
                run = case[phrasing]["agentindex"]
                if run["rank"] is None or run["rank"] > 3:
                    top = run["top"][0] if run["top"] else "nothing"
                    missed.append(
                        f'- `{case["id"]}` ({phrasing}) "{case[phrasing]["query"]}": wanted'
                        f" {', '.join(f'`{a}`' for a in case['answers'])}, got `{top}`"
                    )
        if missed:
            lines += [f"**{corpus['title']}** ({len(missed)})", "", *missed, ""]
    return lines


def _pct(value: float | None) -> str:
    return "–" if value is None else f"{value * 100:.0f}%"


def _num(value: int) -> str:
    return f"{value:,}"


def _ms(value: float | None) -> str:
    return "–" if value is None else f"{value:.1f} ms"
